"use client"

import * as React from "react"
import { Tabs as TabsPrimitive } from "@base-ui/react/tabs"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "cn"

function Tabs({
  className,
  orientation = "horizontal",
  ...props
}: TabsPrimitive.Root.Props) {
  return (
    <TabsPrimitive.Root
      data-slot="tabs"
      data-orientation={orientation}
      className={cn(
        "group/tabs flex gap-2 data-horizontal:flex-col",
        className
      )}
      {...props}
    />
  )
}

const tabsListVariants = cva(
  "group/tabs-list no-scrollbar inline-flex w-fit max-w-full items-center justify-start overflow-x-auto overscroll-x-contain rounded-lg text-muted-foreground group-data-vertical/tabs:h-fit group-data-vertical/tabs:flex-col data-[variant=line]:rounded-none",
  {
    variants: {
      variant: {
        default: "bg-muted",
        line: "gap-1 bg-transparent",
      },
      size: {
        sm: "gap-0.5 p-1",
        md: "gap-0.5 p-1.5",
        lg: "gap-1 p-2",
      },
    },
    defaultVariants: {
      variant: "default",
      size: "sm",
    },
  }
)

function TabsList({
  className,
  variant = "default",
  size = "sm",
  ...props
}: TabsPrimitive.List.Props & VariantProps<typeof tabsListVariants>) {
  const listRef = React.useRef<HTMLDivElement>(null)

  // La tab activa puede quedar fuera de la vista (Configuración tiene 7 y
  // Reportes 6). Al montar y al cambiar de tab, se acerca al centro sin
  // arrastrar la página completa.
  React.useEffect(() => {
    const node = listRef.current
    if (!node) return

    const reveal = () => {
      const active = node.querySelector<HTMLElement>("[data-active]")
      active?.scrollIntoView({ block: "nearest", inline: "nearest" })
    }

    reveal()

    const observer = new MutationObserver(reveal)
    observer.observe(node, {
      subtree: true,
      attributes: true,
      attributeFilter: ["data-active"],
    })

    return () => observer.disconnect()
  }, [])

  return (
    <TabsPrimitive.List
      ref={listRef}
      data-slot="tabs-list"
      data-variant={variant}
      data-size={size}
      className={cn(tabsListVariants({ variant, size }), className)}
      {...props}
    />
  )
}

